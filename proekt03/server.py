# Импортируем стандартный модуль Python для обработки веб-запросов по протоколу HTTP
import http.server

# Импортируем модуль для работы с путями в операционной системе
import os

# Импортируем модуль сокетов для низкоуровневой работы с сетевыми подключениями TCP
import socketserver

# Импортируем модуль для работы с потоками (позволяет выполнять задачи асинхронно в фоне)
import threading

# Импортируем модуль для автоматического открытия страниц в веб-браузере по умолчанию
import webbrowser

# Задаем сетевой порт, на котором сервер будет принимать соединения (8000)
PORT = 8000

# Задаем IP-адрес локального интерфейса (127.0.0.1 — доступ только с этого компьютера)
HOST = "127.0.0.1"


# Создаем собственный класс сервера, наследуясь от стандартного TCP-сервера socketserver
class ReuseAddressTCPServer(socketserver.TCPServer):
  # Включаем флаг SO_REUSEADDR: разрешает повторно занимать порт 8000 сразу после перезапуска
  allow_reuse_address = True


# Объявляем функцию, которая откроет сайт в браузере
def open_browser():
  # Формируем полный URL-адрес и передаем его системному браузеру
  webbrowser.open(f"http://{HOST}:{PORT}")


# Главная функция инициализации и запуска сервера
def run_server():
  # Получаем абсолютный путь к папке, в которой расположен данный файл server.py
  script_dir = os.path.dirname(os.path.abspath(__file__))

  # Переключаем рабочий каталог программы на эту папку (чтобы сервер точно нашел index.html)
  os.chdir(script_dir)

  # Назначаем стандартный обработчик запросов (раздает файлы из текущей папки и открывает index.html)
  handler = http.server.SimpleHTTPRequestHandler

  # Инициализируем TCP-сервер с адресом, портом и обработчиком в контекстном менеджере with
  with ReuseAddressTCPServer((HOST, PORT), handler) as httpd:
    # Выводим в консоль разделительную зеленую линию (код \033[92m включает зеленый цвет)
    print("\033[92m" + "=" * 60)

    # Выводим строку с кликабельным адресом запущенного сервера
    print(f"[*] Локальный веб-сервер запущен: http://{HOST}:{PORT}")

    # Выводим подсказку для пользователя о комбинации клавиш для остановки
    print("[*] Для остановки сервера нажмите Ctrl + C")

    # Сбрасываем цвет консоли обратно на стандартный (\033[0m)
    print("=" * 60 + "\033[0m")

    # Создаем таймер на 0.5 секунды: он запустит open_browser в отдельном потоке после старта сервера
    threading.Timer(0.5, open_browser).start()

    # Блок отлова исключений для корректного выхода из программы
    try:
      # Запускаем бесконечный цикл ожидания и обработки сетевых запросов от браузера
      httpd.serve_forever()

    # Перехватываем нажатие комбинации клавиш Ctrl + C пользователем
    except KeyboardInterrupt:
      # Выводим информационное сообщение желтым цветом (\033[93m) о завершении работы
      print("\n\033[93m[*] Сервер успешно остановлен.\033[0m")


# Проверяем, запущен ли скрипт напрямую, а не импортирован как модуль
if __name__ == "__main__":
  # Запускаем основную функцию сервера
  run_server()